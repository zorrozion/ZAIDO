很有意思，在今天的中国社会里，你一旦相信自己并不能掌控所有的事情，你一旦相信科学和理性并不能够解释所有的事情，对于不可见的世界，对于那些不可见的事物，对于那些不可见的次序，好奇、恐惧和迷信灵的力量，就一定会充满你，成为你价值观的一部分。任何一个自称唯物主义者，一旦面临他心灵中的忧伤、软弱的时候，就会对灵的力量，保持一种宁可信其有不可信其无的实用主义态度。每个人都会有这样的经历，你苦苦地想一件事情，想不出来，穷尽了所有的想法，你的理性走到了一个边界，忽然，灵光一闪，灵台清明，你就想明白了。

在中国的古代禅、佛、道、魔的思想当中，他们对灵的认识，背后没有一位独一的上帝。灵是没有内容、没有圣洁和公义、没有上帝所赐明确的道德诫命。所以，在中国传统文化里，中国人所讲的灵，通常都跟哪几个字连在一起呢？第一，它跟“空”连在一起：空灵；第二，它跟“虚”连在一起：灵虚；第三，它跟“幻”连在一起：灵幻。什么是灵呢？是虚的，是空的，是幻的，因为它没有内容、没有道德次序、没有永恒当中万事以先的耶和华的旨意；它没有在人类的历史当中展开、万事都互相效力的救恩的次序。

如果你不认识独一的真神，对你来说：第一，灵的力量是真实的；第二，灵的力量是妖魔鬼怪，是莫测的命运，是善恶相争的诸神或者是某种企图操纵神秘力量的巫术。这就是耶和华定意要以色列人剪除迦南各族的原因之一，因为迦南各族主要的罪恶，就是各种巫术和交鬼。换言之，他们是一个迷恋灵的力量的文化，他们的电影院里经常演一些捉妖记、第二代妖怪之类的大片，而且票房都很高。所以，神很憎恶。不认识上帝的民族，他们的文化最终将成为魔鬼的消费者，他们的文化最终将成为一种邪灵所充满的文化、一种妖魔鬼怪的文化，一种巫术的文化。

你不要以为巫术，就是真的进入一个庙，很正式地来做什么，其实，巫术充满在我们的日常生活当中。比如说广东人吃东西，说这个像心，吃了补心；这个像脚，吃了补脚。这就是巫术。相信一种神秘的力量是无处不在的，相信一种类比的力量，比如说吃什么补什么，但实际上是不相信独一真神和他的圣洁的灵的文化，是充满了巫术和邪灵的力量的文化。在这样的文化当中，魔鬼用恐惧来统治一切不相信上帝的人，魔鬼用你对偶然的恐惧或者对偶然的迷恋，来统治一切抓不住自己未来的人。

这是一种灵的观念，我们是基督徒，我们相信上帝、我们相信魔鬼的真实性、我们相信圣灵、我们相信灵的世界、我们相信那堕落的天使、我们也相信借着人心中的罪恶，在这个世界上所横行的各种邪灵的力量。

